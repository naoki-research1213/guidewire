ROOT = Path(__file__).resolve().parents[1]
BEAM = ROOT / "vendor/BeamAdapter/src/BeamAdapter/component"
COMMIT = "cac4005bd7c9f266c5c775ab88cebbd7c7fa83c7"

def functions(path, cls, name):
    src = source_file(path).read_text(encoding="utf-8")
    # コメント・文字列中の波括弧は関数終端に数えない。
    masked = re.sub(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
                    lambda m: re.sub(r'[^\n]', ' ', m[0]), src)
    found = []
    for m in re.finditer(r'\bvoid\s+' + cls + r'<DataTypes>::' + name + r'\s*\(', masked):
        opening = masked.index('{', m.end())
        level = 1
        closing = opening + 1
        while level:
            level += (masked[closing] == '{') - (masked[closing] == '}')
            closing += 1
        found.append((src[m.start():opening], src[opening:closing], src[:m.start()].count('\n')+1))
    return found

